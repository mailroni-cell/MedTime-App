# M-195: official indication text (English, Ministry of Health registry) for each row of drugs_il.js, same order.
# Row: [indication (shortened), registration number]. Loaded only when a medicine is opened in the dictionary.
import json, gzip, re, datetime
raw = json.load(gzip.open('data-cache/drugs_raw.json.gz'))
D = json.load(open('data-cache/drugs_app.json', encoding='utf-8'))
by = {}
ws = lambda s: re.sub(r'\s+', ' ', s or '').strip()
for r in raw:
    if r.get('veterinaryUse') == 'כן' or r.get('canceled') == 'כן': continue
    by.setdefault((ws(r['tradeName']), ws(r['dosageFormE'])), r)
def short(s, n=600):
    s = re.sub(r'\s+', ' ', (s or '').replace(' ', ' ')).strip()
    if len(s) <= n: return s
    cut = s[:n]; p = max(cut.rfind('. '), cut.rfind('; '))
    return (cut[:p + 1] if p > n * 0.5 else cut.rsplit(' ', 1)[0]) + ' …'
rows, miss = [], 0
for d in D:
    if not d['a']: continue
    r = by.get((ws(d['e']), ws(d['fe'])))
    if not r: miss += 1
    rows.append([short(r['indication']) if r else '', r['regNumber'] if r else ''])
out = ('/* M-195: official indication (English) and registration number from the Ministry of Health registry, same order as drugs_il.js. '
       'Generated by tools/make_ind_js.py on %s. */\nwindow.IL_IND=' % datetime.date.today().isoformat()) + json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + ';\n'
open('app/src/main/assets/drugs_ind.js', 'w', encoding='utf-8').write(out)
print(len(rows), 'rows,', miss, 'unmatched,', len(out.encode()), 'bytes')
